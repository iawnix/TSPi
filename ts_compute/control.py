def _load_act(workspace: Path, act_id: str) -> dict[str, Any]:
    registry = _read_object(workspace / "research_acts.json", "ResearchAct registry")
    if registry.get("schema_version") != "ts-research-act-registry/2":
        raise ComputeContractError("invalid ResearchAct registry")
    matches = [
        item
        for item in registry.get("acts", [])
        if isinstance(item, dict) and item.get("act_id") == act_id
    ]
    if len(matches) != 1:
        raise ComputeContractError(f"unknown ResearchAct: {act_id}")
    return matches[0]


def _validate_intent(intent: dict[str, Any]) -> None:
    schema_version = intent.get("schema_version")
    if schema_version != "ts-calculation-intent/4":
        raise ComputeContractError(f"unsupported calculation intent schema_version: {schema_version}")
    validate_compute_contract(INTENT_SCHEMA, intent)


def _validate_intent_act_scope(workspace: Path, intent: dict[str, Any], act: dict[str, Any]) -> None:
    if act.get("schema_version") != "ts-research-act/2":
        raise ComputeContractError("calculations require a ts-research-act/2 owner")
    if act.get("status") != "open":
        raise ComputeContractError("calculations require an open ResearchAct")
    if intent.get("act_id") != act.get("act_id"):
        raise ComputeContractError("calculation intent owner does not match its ResearchAct")

    if intent.get("attempt_kind") != "recalculation":
        return
    recalculation = intent.get("recalculation_ref")
    source_act = recalculation.get("source_act") if isinstance(recalculation, dict) else None
    try:
        _load_act(workspace, str(source_act))
    except ComputeContractError as exc:
        raise ComputeContractError(f"recalculation_ref.source_act does not exist: {source_act}")
    source_intent = recalculation.get("source_intent_id")
    if source_intent is not None:
        source_matches = [
            *list((workspace / "acts" / source_act).glob(f"attempts/{source_intent}/intent.json")),
        ]
        if len(source_matches) != 1:
            raise ComputeContractError(
                f"recalculation_ref.source_intent_id must identify one local source attempt: {source_intent}"
            )


def _workspace_ref(workspace: Path, value: str, *, read: bool) -> str:
    text = str(value).replace("\\", "/").lstrip("@")
    if PurePosixPath(text).is_absolute():
        raise ComputeContractError(f"workspace path must be relative: {value}")
    normalized = posixpath.normpath(text)
    if normalized in {"", ".", ".."} or normalized.startswith("../"):
        raise ComputeContractError(f"invalid workspace path: {value}")
    path = (workspace / normalized).resolve()
    try:
        path.relative_to(workspace)
    except ValueError as exc:
        raise ComputeContractError(f"workspace path escapes root: {value}") from exc
    if read:
        if not path.is_file():
            raise ComputeContractError(f"workspace input does not exist: {normalized}")
        try:
            path.resolve(strict=True).relative_to(workspace.resolve(strict=True))
        except ValueError as exc:
            raise ComputeContractError(f"workspace input symlink escapes root: {normalized}") from exc
    return normalized


