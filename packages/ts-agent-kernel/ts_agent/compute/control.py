def _result(
    intent: dict[str, Any],
    *,
    job_id: str | None = None,
    state: str,
    program_status: str,
    exit_status: int | None = None,
    artifact_refs: list[str] | None = None,
    parser_facts: dict[str, Any] | None = None,
    task_validation: dict[str, Any] | None = None,
    error_class: str | None = None,
    control: dict[str, Any] | None = None,
    provenance: dict[str, Any] | None = None,
) -> dict[str, Any]:
    result = {
        "schema_version": "ts-calculation-result/2",
        "job_id": job_id,
        "intent_id": intent["intent_id"],
        "node_id": intent["node_id"],
        "capability": intent["capability"],
        "capability_version": intent["capability_version"],
        "expected_output_roles": list(intent["expected_output_roles"]),
        "state": state,
        "program_status": program_status,
        "exit_status": exit_status,
        "artifact_refs": list(dict.fromkeys(artifact_refs or [])),
        "parser_facts": parser_facts or {},
        "error_class": error_class,
        "provenance": {
            "backend": intent["backend"],
            "capability": intent["capability"],
            "capability_version": intent["capability_version"],
            "capability_descriptor_digest": intent["capability_descriptor_digest"],
            "intent_digest": sha256_json(intent),
            "intent_schema": intent["schema_version"],
            "attempt_kind": intent["attempt_kind"],
            "attempt_lineage": _result_attempt_lineage(intent),
            "remote_authority": "execution_mirror" if intent.get("execution_target", {}).get("kind") == "remote" else None,
            **(provenance or {}),
        },
    }
    if task_validation is not None:
        result["task_validation"] = task_validation
    if control is not None:
        result["control"] = control
    validate_compute_contract(RESULT_SCHEMA, result)
    return result


